export function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

let nextNum = 1009;

/**
 * Shared factory used both by the authenticated admin "create enterprise"
 * route and the public self-registration endpoint, so both paths produce
 * consistent records with guaranteed-unique IDs.
 */
export function createEnterprise(body = {}, overrides = {}) {
  const name = body.name || "Untitled Enterprise";
  const sector = body.sector || masterData.sectors[0];
  const region = body.region || masterData.regions[0];
  const zone = body.zone || "Central";
  
  const item = {
    id: `ENT-${nextNum++}`,
    name,
    tradeName: body.tradeName || name,
    slug: slugify(name) || `enterprise-${Date.now()}`,
    tin: body.tin || `00${Math.floor(10000000 + Math.random() * 90000000)}`,
    sector,
    subsector: body.subsector || `${sector} Manufacturing`,
    isic: body.isic || "1000",
    region,
    zone,
    size: body.size || masterData.sizes[0],
    ownership: body.ownership || "Domestic private",
    employees: Number(body.employees) || 25,
    exportStatus: body.exportStatus || "Domestic",
    status: body.status || "Pending verification",
    establishedYear: Number(body.establishedYear) || new Date().getFullYear(),
    lat: Number(body.lat) || (region === "Oromia" ? 8.54 : region === "Amhara" ? 11.59 : region === "Tigray" ? 13.49 : 9.02),
    lng: Number(body.lng) || (region === "Oromia" ? 39.27 : region === "Amhara" ? 37.39 : region === "Tigray" ? 39.47 : 38.75),
    manager: body.manager || "Enterprise Officer",
    phone: body.phone || "+251 91 100 2233",
    email: body.email || `info@${slugify(name)}.et`,
    industrialPark: body.industrialPark || "—",
    capacityUtilization: Number(body.capacityUtilization) || 65,
    theme: siteThemes.includes(body.theme) ? body.theme : siteThemes[Math.floor(Math.random() * siteThemes.length)],
    tagline: body.tagline || `Quality ${sector.toLowerCase()} manufacturing from ${region}, Ethiopia`,
    about: body.about || `${name} is a registered ${sector.toLowerCase()} manufacturing enterprise established in ${region}, ${zone}. Committed to national industrial excellence and production quality.`,
    products: Array.isArray(body.products) && body.products.length ? body.products : DEFAULT_PRODUCTS[sector] || DEFAULT_PRODUCTS["Food & Beverage"],
    source: "admin",
    ...overrides,
  };
  enterprises.push(item);
  return item;
}
